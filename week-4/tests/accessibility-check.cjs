// Complements axe with keyboard, contrast, preference, and fallback checks.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const base = process.env.LAUNCHPAD_BASE_URL || 'http://127.0.0.1:8024/';
const evidence = path.resolve(__dirname,'../evidence');
const checks=[];
const contrast=(hex1,hex2)=>{
  const luminance=hex=>hex.match(/[a-f\d]{2}/gi).map(x=>parseInt(x,16)/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4).reduce((a,x,i)=>a+x*[.2126,.7152,.0722][i],0);
  const a=luminance(hex1),b=luminance(hex2); return (Math.max(a,b)+.05)/(Math.min(a,b)+.05);
};
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.LAUNCHPAD_BROWSER?{executablePath:process.env.LAUNCHPAD_BROWSER}:{})});
  const context=await browser.newContext({viewport:{width:390,height:844}});
  const page=await context.newPage();
  await page.goto(base);
  await page.keyboard.press('Tab');
  assert.equal(await page.locator(':focus').getAttribute('class'),'skip-link');
  await page.screenshot({path:path.join(evidence,'skip-link.png')});
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.activeElement.id==='main');
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await page.keyboard.press('Tab');
  assert.equal(await page.locator(':focus').getAttribute('href'),'#notes');
  checks.push('First Tab exposes skip link; Enter focuses main; next Tab reaches main content');
  await page.locator('#menu-toggle').focus();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Tab');
  assert.equal(await page.locator(':focus').textContent(),'Learning notes');
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.activeElement.id==='notes-title');
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'),'false');
  checks.push('Keyboard menu link closes menu and transfers focus to destination heading');
  await page.setViewportSize({width:1440,height:900});
  await page.waitForFunction(()=>document.getElementById('menu-toggle').hidden);
  await page.locator('#main-nav a').first().focus();
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.activeElement.id==='menu-toggle');
  await page.setViewportSize({width:1440,height:900});
  await page.waitForFunction(()=>document.activeElement===document.querySelector('#main-nav a'));
  checks.push('Breakpoint changes recover focus from hidden desktop links and phone toggle');
  const originalButton=await page.locator('[data-save="layout"] span').elementHandle();
  await page.locator('#note-search').fill('grid');
  assert.equal(await originalButton.evaluate(el=>el.isConnected),true);
  await page.locator('#note-search').fill('');
  checks.push('Search does not replace save-button DOM');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto');
  assert.equal(await page.locator('.save-note').first().evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
  await page.locator('#learner-name').fill('Yash');
  await page.locator('#plan-topic').selectOption('layout');
  await page.locator('#plan-minutes').selectOption('30');
  await page.locator('#plan-goal').fill('Build a responsive project gallery.');
  await page.getByRole('button',{name:'Create my plan'}).click();
  assert.equal(await page.locator('#plan-result').evaluate(el=>getComputedStyle(el).animationName),'none');
  checks.push('Reduced motion disables smooth scroll, button transitions, and plan reveal');
  await page.emulateMedia({forcedColors:'active'});
  await page.locator('#plan-result').focus();
  await page.keyboard.press('Tab');
  await page.keyboard.press('Tab');
  assert.equal(await page.locator(':focus').getAttribute('id'),'edit-plan');
  assert.notEqual(await page.locator('#edit-plan').evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  checks.push('Forced-colors preference retains a visible focus outline');
  await page.emulateMedia({forcedColors:'none'});
  await page.locator('#new-plan').click();
  const scans=[];
  async function scan(state) {
    await page.addScriptTag({path:require.resolve('axe-core/axe.min.js')});
    const result=await page.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa','best-practice']}}));
    scans.push({state,violations:result.violations,incomplete:result.incomplete.map(x=>({id:x.id,targets:x.nodes.map(n=>n.target)})),passes:result.passes.length});
    assert.equal(result.violations.length,0,state);
  }
  await scan('desktop form');
  await page.getByRole('button',{name:'Create my plan'}).click();
  await scan('invalid form');
  await page.locator('#learner-name').fill('Yash');
  await page.locator('#plan-topic').selectOption('layout');
  await page.locator('#plan-minutes').selectOption('30');
  await page.locator('#plan-goal').fill('Build a responsive project gallery.');
  await page.getByRole('button',{name:'Create my plan'}).click();
  await scan('generated plan');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#menu-toggle').click();
  await scan('open mobile menu');
  checks.push('Axe reports zero violations in desktop, invalid form, generated plan, and mobile-menu states');
  await page.setViewportSize({width:320,height:800});
  await page.addStyleTag({content:'html { font-size: 200%; }'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),320);
  await page.locator('#new-plan').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),320);
  await page.locator('#guide-layout summary').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),320);
  checks.push('At 320px and 200% root text size, generated plan, form, and expanded guide have no horizontal overflow');
  const noJs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const fallback=await noJs.newPage();
  await fallback.goto(base);
  await fallback.keyboard.press('Tab');
  await fallback.keyboard.press('Enter');
  assert.equal(await fallback.locator(':focus').getAttribute('id'),'main');
  assert.equal(await fallback.locator('#main-nav').isVisible(),true);
  checks.push('Without JavaScript the skip link focuses main and all navigation remains visible');
  const ratios=[['Body ink on paper','#25272c','#faf9f5',4.5],['Muted text on darkest section','#61636b','#eeeee7',4.5],['Button white on purple','#ffffff','#5147b7',4.5],['Input boundary on white','#85838f','#ffffff',3],['Error text on white','#a43737','#ffffff',4.5]].map(([name,a,b,min])=>({name,ratio:Number(contrast(a,b).toFixed(2)),minimum:min}));
  ratios.forEach(r=>assert.ok(r.ratio>=r.minimum,r.name));
  checks.push('Measured text, button, error, and control-boundary colors meet their contrast thresholds');
  fs.writeFileSync(path.join(evidence,'accessibility-results.json'),JSON.stringify({date:'2026-10-22',checks,ratios,scans},null,2));
  console.log(`Passed ${checks.length} additional accessibility and performance regression checks.`);
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
